/**
 * Concatenate OWWA theme partials → public/css/filament/admin/owwa-theme.css
 * Usage: npm run build:owwa-theme
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const partialsDir = path.join(root, 'resources/css/owwa');
const outPath = path.join(root, 'public/css/filament/admin/owwa-theme.css');

/** Build order must match original cascade (contiguous split). */
const PARTIALS = [
    '_tokens.css',
    '_base.css',
    '_dashboard.css',
    '_forms.css',
    '_tables.css',
    '_charts.css',
    '_pages.css',
    '_modals.css',
    '_misc.css',
];

const header = `/**
 * OWWA Inventory System — UI Theme (GENERATED)
 * Brand: Navy #003366 · Crimson #c41e3a
 *
 * Do not edit this file directly.
 * Edit partials in resources/css/owwa/ then run: npm run build:owwa-theme
 */

`;

const bodies = PARTIALS.map((name) => {
    const filePath = path.join(partialsDir, name);
    if (!fs.existsSync(filePath)) {
        throw new Error(`Missing partial: ${filePath}`);
    }
    return fs.readFileSync(filePath, 'utf8').trimEnd();
});

const output = header + bodies.join('\n\n') + '\n';
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, output, 'utf8');

console.log(`Wrote ${outPath} (${output.length} bytes from ${PARTIALS.length} partials)`);
